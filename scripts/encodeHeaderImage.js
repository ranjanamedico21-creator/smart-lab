'use strict';

// ═══════════════════════════════════════════════════════════════════════
// scripts/encodeHeaderImages.js
//
// Converts header/footer PNG images to base64 data-URIs
// and writes them to your .env file.
//
// Run from project root:
//   node scripts/encodeHeaderImages.js
// ═══════════════════════════════════════════════════════════════════════

const fs   = require('fs');
const path = require('path');

// ── Always resolve paths relative to THIS script's location ─────────
// scripts/ is one level inside project root, so go up one level
const PROJECT_ROOT  = path.resolve(__dirname, '..');
const ENV_FILE      = path.join(PROJECT_ROOT, '.env');
const HEADER_PATH   = path.join(PROJECT_ROOT, 'images', 'report-header.jpg');
const FOOTER_PATH   = path.join(PROJECT_ROOT, 'public', 'assets', 'report-footer.png');

// ── Logging helpers ──────────────────────────────────────────────────
const ok   = (msg) => console.log(`  ✓  ${msg}`);
const warn = (msg) => console.log(`  ⚠  ${msg}`);
const err  = (msg) => console.log(`  ✗  ${msg}`);
const info = (msg) => console.log(`     ${msg}`);

console.log('\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
console.log('  Report Header/Footer Image Encoder');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

console.log('📁 Paths resolved:');
info(`Project root : ${PROJECT_ROOT}`);
info(`.env file    : ${ENV_FILE}`);
info(`Header image : ${HEADER_PATH}`);
info(`Footer image : ${FOOTER_PATH}`);
console.log();

// ── Check .env exists ────────────────────────────────────────────────
if (!fs.existsSync(ENV_FILE)) {
    warn(`.env not found at: ${ENV_FILE}`);
    info('Creating a new .env file...');
    fs.writeFileSync(ENV_FILE, '# Auto-generated by encodeHeaderImages.js\n');
    ok('.env created');
}

// ── Encode image to base64 data-URI ─────────────────────────────────
const encodeImage = (imagePath, label) => {
    console.log(`🖼  Processing ${label}...`);
    info(`Path: ${imagePath}`);

    if (!fs.existsSync(imagePath)) {
        warn(`File not found — skipping ${label}`);
        info(`Place your image at: ${imagePath}`);
        console.log();
        return null;
    }

    try {
        const buffer   = fs.readFileSync(imagePath);
        const base64   = buffer.toString('base64');
        const origKb   = Math.round(buffer.length    / 1024);
        const b64Kb    = Math.round(base64.length / 1024);
        const dataUri  = `data:image/png;base64,${base64}`;

        ok(`Encoded successfully`);
        info(`Original size : ${origKb} KB`);
        info(`Base64 size   : ${b64Kb} KB`);
        console.log();
        return dataUri;
    } catch (e) {
        err(`Failed to encode: ${e.message}`);
        console.log();
        return null;
    }
};

// ── Write / update a key in .env ─────────────────────────────────────
const writeEnvVar = (envContent, key, value) => {
    const regex   = new RegExp(`^${key}=.*$`, 'm');
    const newLine = `${key}=${value}`;

    if (regex.test(envContent)) {
        info(`Updating existing key: ${key}`);
        return envContent.replace(regex, newLine);
    } else {
        info(`Adding new key: ${key}`);
        // Ensure file ends with newline before appending
        const separator = envContent.endsWith('\n') ? '' : '\n';
        return `${envContent}${separator}${newLine}\n`;
    }
};

// ── Main ─────────────────────────────────────────────────────────────
const headerUri = encodeImage(HEADER_PATH, 'Header Image');
const footerUri = encodeImage(FOOTER_PATH, 'Footer Image (optional)');

if (!headerUri && !footerUri) {
    console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
    err('No images were found. .env was NOT modified.');
    console.log('\n📋 Next steps:');
    console.log(`   1. Crop your letterhead header from the PDF`);
    console.log(`   2. Save it as:  ${HEADER_PATH}`);
    console.log(`   3. Run this script again\n`);
    process.exit(1);
}

console.log('💾 Writing to .env...');
let envContent = fs.readFileSync(ENV_FILE, 'utf8');

if (headerUri) envContent = writeEnvVar(envContent, 'BRAND_HEADER_IMAGE', headerUri);
if (footerUri) envContent = writeEnvVar(envContent, 'BRAND_FOOTER_IMAGE', footerUri);

fs.writeFileSync(ENV_FILE, envContent, 'utf8');

console.log();
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
ok('Done! .env updated successfully.');
console.log();
console.log('📋 Next steps:');
console.log('   1. Restart your Node.js server');
console.log('   2. Download a PDF report to verify the header');
if (!footerUri) {
    console.log('   3. (Optional) Add report-footer.png and re-run for footer image');
}
console.log();